"""Перечень вопросов, без ответа на которые трекер не показывает ход работ.
Читает tracker/merged.json и tracker/merge_report.json (их пишет merge_sources.py), пишет tracker/questions.json."""
import calendar, collections, datetime, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TODAY = datetime.date(2026, 10, 20)
CLOSED = ('Выполнено, акта нет', 'Принято, акт есть', 'Снято', 'Отложено на зиму')
MN = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь']


def mend(m):
    y, mm = map(int, m.split('-'))
    return datetime.date(y, mm, calendar.monthrange(y, mm)[1])


def pl(n, a, b, c):
    m, h = n % 10, n % 100
    return a if m == 1 and h != 11 else b if 2 <= m <= 4 and not 12 <= h <= 14 else c


def row(i, note=''):
    return dict(addr=i['addr'], work=i['work'], month=MN[int(i['month'][5:]) - 1], status=i['status'], master=i['master'] or '—',
                ex=i['ex'], note=note or i.get('check') or '')


def main():
    M = json.loads((ROOT / 'tracker' / 'merged.json').read_text(encoding='utf-8'))['items']
    R = json.loads((ROOT / 'tracker' / 'merge_report.json').read_text(encoding='utf-8'))
    op = [i for i in M if i['status'] not in CLOSED]
    od = [i for i in op if mend(i['month']) < TODAY]
    Q = []

    def q(to, topic, text, why, items, term):
        Q.append(dict(n=len(Q) + 1, to=to, topic=topic, text=text, why=why, count=len(items), term=term, items=items))

    # ---------- ПТО ----------
    noact = [i for i in M if i['status'] == 'Выполнено, акта нет']
    by = collections.Counter(i['act'] or 'не указано' for i in noact)
    q('ПТО', 'Акты', 'По %d выполненным работам нет акта. Отметка у исполнителей: %s. По каждой нужен номер и дата акта или срок, когда акт будет.'
      % (len(noact), ', '.join('%s — %d' % (k, v) for k, v in by.most_common())),
      'Пока акта нет, работа не считается принятой: в трекере она «выполнено, акта нет», а в отчёте УК её нельзя показать закрытой.',
      [row(i, 'акт: ' + (i['act'] or 'не указано')) for i in sorted(noact, key=lambda x: x['month'])], 'до 30.10')
    sam = [i for i in M if i['act'] == 'не знают, как подписать']
    q('ПТО', 'Акты', 'Исполнители пишут «как подписывать (самовар)» по %d работам. Кто и в каком порядке подписывает акты на эти работы?' % len(sam),
      'Без порядка подписания эти работы так и останутся без акта.', [row(i) for i in sam], 'до 23.10')
    late = [i for i in od if i['status'] in ('Не начато', 'Нет статуса')]
    q('ПТО', 'Сроки', '%d работ с прошедшим месяцем плана не начаты или без статуса. По каждой: новый месяц выполнения или снять с плана.' % len(late),
      'Сейчас они висят просроченными и искажают процент выполнения и нагрузку исполнителей.', [row(i) for i in late], 'до 23.10')
    exch = [i for i in M if i['check'].find('исполнитель:') >= 0]
    q('ПТО', 'Исполнитель', 'У %d работ по отметке 23.09 исполнитель СВОИ, а в файле исполнителей 08.10 — «ПТО». Кто выполняет: СВОИ или подрядчик?' % len(exch),
      'От этого зависит, кто отмечает работу в трекере и к кому вопросы по сроку.', [row(i) for i in exch], 'до 23.10')
    nex = [i for i in op if i['ex'] == 'Не распределено']
    q('ПТО', 'Исполнитель', '%d открытых работ без исполнителя (ни СВОИ, ни подрядчик). Назначить.' % len(nex),
      'Работу без исполнителя никто не отмечает, кроме администратора.', [row(i) for i in nex], 'до 23.10')
    only_ex = [i for i in M if i['only'] == 'exec']
    q('ПТО', 'Состав плана', '%d работы есть в файле исполнителей, но их нет в годовом плане 16.10. Их удалили из плана или забыли?' % len(only_ex),
      'Исполнитель считает их выполненными, а в плане их нет: деньги и акты не сойдутся.', [row(i) for i in only_ex], 'до 23.10')
    fsd = [i for i in M if 'факт:' in i['check']]
    q('ПТО', 'Факт', 'По %d работам фактическая сумма в плане и у исполнителей разная. Какая верная?' % len(fsd),
      'Фактическая сумма нужна для отчёта по дому.', [row(i) for i in fsd], 'до 23.10')
    nosum = [i for i in op if not i['sum']]
    q('ПТО', 'Бюджет', 'У %d открытых работ нет оценки стоимости. Проставить хотя бы ориентировочную.' % len(nosum),
      'Без оценки трекер не показывает, сколько денег осталось освоить по плану.', [row(i) for i in nosum], 'до 30.10')
    uk = [i for i in M if i['uk'] in ('УК В', 'УК МИДЕ')]
    q('ПТО', 'Справочники', 'В названии УК ошибки: «УК В» и «УК МИДЕ». Какая это УК?', 'Иначе работы этих домов не попадают в отбор по УК.', [row(i, i['uk']) for i in uk], 'при обновлении плана')

    # ---------- мастера ----------
    stuck = [i for i in od if i['status'] in ('В работе', 'На контроле', 'Передано исполнителю')]
    cnt = collections.Counter(i['master'] or 'без мастера' for i in stuck)
    q('Мастера участков', 'Сроки', '%d работ «в работе» или «на контроле», а месяц плана прошёл (%s). По каждой: дата завершения и что мешает.'
      % (len(stuck), ', '.join('%s — %d' % (k, v) for k, v in cnt.most_common())),
      'Без даты завершения трекер показывает только «просрочено», а не когда ждать результат.', [row(i) for i in stuck], 'до 23.10')
    unc = [i for i in M if i['status'] == 'Требует уточнения']
    q('Мастера участков', 'Решения', '%d работ стоят с вопросами («?????», «Почему мы???», «не может отключить Водоканал», «нужна замена ГВС, а не ЦО»). Нужно решение по каждой.' % len(unc),
      'Пока решения нет, работа не движется и не может быть ни выполнена, ни снята.', [row(i, i['src_note'].split(' · ')[-1]) for i in unc], 'до 23.10')
    acc = [i for i in M if 'доступ' in i['src_note'].lower() and i['status'] not in CLOSED]
    q('Мастера участков', 'Доступ', 'По %d работам собственники не дают доступ. Отправлены ли письменные уведомления, составлен ли акт недопуска?' % len(acc),
      'С актом недопуска работу можно законно перенести или снять, без него она висит в просрочке.', [row(i) for i in acc], 'до 23.10')
    nom = [i for i in op if not i['master']]
    q('Мастера участков', 'Ответственный', '%d открытых работ без мастера участка. Назначить ответственного.' % len(nom),
      'Сводка «Мастера участков» не покажет эти работы, спросить по ним не с кого.', [row(i) for i in nom], 'до 23.10')
    sev = [i for i in M if i['master'] == 'Мастер участка (Север)']
    q('Руководство', 'Ответственный', '«Мастер участка (Север)» указан у %d %s. Кто это по фамилии?' % (len(sev), pl(len(sev), 'работы', 'работ', 'работ')),
      'В трекере ответственным должен быть конкретный человек.', [row(i) for i in sev], 'до 23.10')
    q('Руководство', 'Ответственный', 'Алиев Р.Р. (мастер, отдельный лист в файле исполнителей) и Алеев Р.Р. (электрик СВОИ) — это два разных человека?',
      'Если это один человек, его работы в трекере разделятся на двоих.', [], 'до 23.10')

    # ---------- Битрикс24 ----------
    stale = [i for i in M if i['status'] in ('Выполнено, акта нет', 'Принято, акт есть') and i['bx_stage'] == 'Запланировано']
    q('Ответственный за Битрикс24', 'Стадии', 'В %d выполненных работах стадия в Битрикс24 до сих пор «Запланировано». Кто и когда переводит стадии?' % len(stale),
      'Если стадии не двигаются, Битрикс24 нельзя использовать для контроля, а сведение будет каждый раз зависеть от Excel.', [row(i, 'стадия: Запланировано') for i in stale], 'до 30.10')
    q('Ответственный за Битрикс24', 'Стадии', 'Что означает стадия «Успешно»: работа принята с актом КС-2 или только выполнена? Сейчас «Успешно» стоит и у работ без акта.',
      'От ответа зависит, считать ли такие работы принятыми.', [], 'до 23.10')
    st = [i for i in M if 'статус расходится' in i['check']]
    q('Ответственный за Битрикс24', 'Стадии', 'По %d работам ПТО или исполнитель отметили «выполнено», а в Битрикс24 стадия «В работе» или «Просрочено». Где правда?' % len(st),
      'Трекер сейчас верит отметке «выполнено», но это надо подтвердить.', [row(i) for i in st], 'до 23.10')
    junk = R.get('Битрикс24: тестовые и пустые записи', [])
    q('Ответственный за Битрикс24', 'Чистота данных', '%d %s («ТЕСТ», «123», без адреса, ответственный «Тестович Тест»). Удалить.' % (len(junk), pl(len(junk), 'тестовая или пустая карточка', 'тестовые или пустые карточки', 'тестовых или пустых карточек')),
      'Они попадают в отчёты Битрикс24 и искажают количество работ.',
      [dict(addr=r['addr_raw'], work=r['work'] or '(пусто)', month=MN[int(r['month'][5:]) - 1], status=r['stage'], master=r['resp'] or '—', ex='', note='строка %d выгрузки' % r['src_row']) for r in junk], 'до 23.10')
    dup = R.get('Битрикс24: повторная карточка той же работы', [])
    q('Ответственный за Битрикс24', 'Чистота данных', '%d работ заведены в Битрикс24 дважды. Оставить одну карточку.' % len(dup), 'Двойные карточки дают двойной счёт.',
      [dict(addr=r['addr_raw'], work=r['work'], month=MN[int(r['month'][5:]) - 1], status=r['stage'], master=r['resp'] or '—', ex='', note='строка %d выгрузки' % r['src_row']) for r in dup], 'до 23.10')
    adr = [i for i in M if 'другой адрес' in i['check']]
    q('ПТО', 'Адреса', 'У %d работ адрес в Битрикс24 не совпадает с годовым планом (например, Пушкарёва 70 и Пушкарева 74, Поливенская 27 и 29, Орлова 2 и 27). Какой адрес верный?' % len(adr),
      'Работа на неверном доме попадёт не в тот отчёт перед собственниками.', [row(i) for i in adr], 'до 23.10')
    obx = [i for i in M if i['only'] == 'bx']
    q('ПТО', 'Состав плана', '%d работ есть только в Битрикс24, в годовом плане их нет (в том числе Карла Либкнехта 22 — 200 000 ₽, Минаева 34 — 159 291 ₽). Внести в план?' % len(obx),
      'Иначе годовой план занижен, а работа выпадает из сводки ПТО.', [row(i) for i in obx], 'до 23.10')
    bad = R.get('Битрикс24: дата завершения раньше начала', [])
    q('Ответственный за Битрикс24', 'Сроки', 'В %d карточках дата завершения раньше даты начала. Исправить даты.' % len(bad),
      'По таким карточкам нельзя посчитать срок и просрочку.',
      [dict(addr=r['addr_raw'], work=r['work'], month=MN[int(r['month'][5:]) - 1], status=r['stage'], master=r['resp'] or '—', ex='',
            note='начало %s, завершение %s' % ('.'.join(reversed(r['start'].split('-'))), '.'.join(reversed(r['end'].split('-'))))) for r in bad], 'до 23.10')
    nau = R.get('Битрикс24: ответственный Наумова, мастер другой', [])
    q('Ответственный за Битрикс24', 'Ответственный', 'Поле «Ответственный за участок» пустое в 205 карточках, а в %d %s стоит Наумова Т.Ю., хотя мастер другой. Это мастер участка или тот, кто завёл карточку?' % (len(nau), pl(len(nau), 'новой карточке', 'новых карточках', 'новых карточках')),
      'Если в поле не мастер, по Битрикс24 нельзя понять, кто отвечает за работу.', [dict(addr=a, work=w, month='', status='', master=m, ex='', note='в Битрикс24: Наумова Т.Ю.') for a, w, m in nau], 'до 23.10')
    mc = [i for i in M if 'мастер:' in i['check']]
    if mc:
        q('Ответственный за Битрикс24', 'Ответственный', 'По %d работе мастер у исполнителей и в Битрикс24 разный. Кто ответственный?' % len(mc), 'Нужен один ответственный.', [row(i) for i in mc], 'до 23.10')
    import re
    whole = sum(1 for i in M if re.match(r'срок 01\.(\d\d)\.2026 – (28|29|30|31)\.\1\.2026', i['bx_dates']))
    q('Руководство', 'Сроки', 'Срок в Битрикс24 почти у всех карточек — «с 1-го по последнее число месяца» (%d из %d). Нужна плановая дата завершения по каждой работе: кто её ставит и когда?' % (whole, sum(1 for i in M if i['in_bx'])),
      'Без даты трекер видит просрочку только после конца месяца и не показывает, что сорвётся на этой неделе.', [], 'до 30.10')

    # ---------- регламент ----------
    q('Руководство', 'Регламент', 'Где ведётся статус работы: в Битрикс24, в годовом плане ПТО или в трекере? Сейчас три источника расходятся, и каждый раз их приходится сводить вручную.',
      'Пока источник не один, трекер показывает сводную картину на дату выгрузки, а не текущую.', [], 'до 23.10')
    q('Руководство', 'Регламент', 'Утвердить единый список статусов и их соответствие: у исполнителей «на контроле», «зима», «?????»; в Битрикс24 «Запланировано», «Успешно», «Просрочено»; в плане цвет строки.',
      'Без общего словаря одна и та же работа выглядит по-разному в каждом файле. Предлагаемое соответствие — на листе «Словарь статусов».', [], 'до 23.10')
    q('Руководство', 'Регламент', 'Кто и как часто обновляет данные? Предложение: исполнители — статус и комментарий по пятницам, ПТО — акты и факт по пятницам, Битрикс24 — стадия в день изменения.',
      'Трекер показывает ход работ, только если данные обновляются по графику.', [], 'до 23.10')
    order = ['ПТО', 'Мастера участков', 'Ответственный за Битрикс24', 'Руководство']
    Q.sort(key=lambda x: (order.index(x['to']), x['n']))
    for n, x in enumerate(Q, 1):
        x['n'] = n
    out = dict(generated=TODAY.isoformat(), questions=Q)
    (ROOT / 'tracker' / 'questions.json').write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf-8')
    print(len(Q), 'вопросов;', sum(x['count'] for x in Q), 'позиций в перечнях')


if __name__ == '__main__':
    main()
