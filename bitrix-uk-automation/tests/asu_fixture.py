"""Вымышленный журнал заявок АСУ в формате выгрузки ADocumentJournal_appealss."""
import datetime as dt

import openpyxl

HEADER = ['№', 'Помещение', 'Время создания', 'Автор', 'Содержание', 'Тип', 'Дом', 'Источник', 'Заявитель',
          'Реакция жильца', 'Исполнитель', 'Комментарий', 'Адрес', 'Удобное время', 'Статус']
APPLICANT = 'Тестова Тамара Тестовна'
PHONE = '8 (900) 000-11-22'


def row(num, created, content, kind, house, comment, status, room='5', reaction=None, executor='Мастеров М. (Мастер)'):
    return [num, room, created, 'Диспетчер Д. Д.', content, kind, house, 'АСУ', APPLICANT, reaction, executor,
            comment, f'{house}, кв. {room}', None, status]


def make_journal(path, rows=None, header=HEADER):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.append(['Журнал Заявки'])
    ws.append(['Параметры фильтра:', 'Адрес', 'АСУ,'])
    ws.append([None, 'Время создания', 'От_ и До_ 01.03.2026 00:01 07.03.2026 17:19'])
    ws.append(['Сортировка', 'по номеру'])
    ws.append(['Сформирован', None, '07.03.2026'])
    ws.append([])
    ws.append(header)
    d = lambda day, h, m=0: dt.datetime(2026, 3, day, h, m)  # noqa: E731
    for r in rows if rows is not None else [
        row(1001, d(1, 10), f'Течь с потолка в коридоре, звонить {PHONE}', 'Сантехника', 'ул. Ленина, 10',
            'На основании: Задача № 5001\n01.03.2026 г., 10:02 Диспетчеров Д. Д.', 'Закрыт', reaction=5),
        row(1002, d(1, 11), 'Стоят колодцы во дворе', None, 'ул Ленина, 10',
            'Передано в водоканал по тел. 123456\n01.03.2026 г., 12:05 Диспетчеров Д. Д.', 'Третья\nсторона'),
        row(1003, d(2, 9), 'Не работает домофон', 'Домофоны', 'ул. Тихая, 4',
            'по эл. почте\n02.03.2026 г., 09:30 Диспетчеров Д. Д.', 'Третья\nсторона'),
        row(1004, d(2, 10), 'Холодный полотенцесушитель', 'Сантехника', 'ул. Тихая, 4',
            'Контроль качества Источник: Оценка: 1\n03.03.2026 г., 08:00 Диспетчеров Д. Д.', 'Закрыт',
            reaction='Не выполнено'),
        row(1005, d(3, 8), 'Нет горячей воды', 'Обслуживание систем горячего водоснабжения', 'ул. Тихая, 4',
            '', 'В работе'),
        row(1006, d(4, 8), 'Нет ГВС в квартире', 'Обслуживание систем горячего водоснабжения', 'ул. Тихая, 4',
            'Ждут с утра\n04.03.2026 г., 09:00 Диспетчеров Д. Д.', 'В работе'),
        row(1007, d(5, 8), 'Нет света возле лифта на 9 этаже', 'Электрика', 'ул. Тихая, 4',
            'На основании: Задача № 5007\n05.03.2026 г., 09:01 Диспетчеров Д. Д.', 'Новый'),
        row(1008, d(5, 9), 'Лифт не работает, застряли', None, 'ул. Тихая, 4',
            'На основании: Задача № 5008\n05.03.2026 г., 09:05 Диспетчеров Д. Д.', 'В работе'),
        row(1009, d(5, 10), 'Нет отопления в квартире', 'Обслуживание систем отопления', 'ул. Тихая, 4',
            'На основании: Задача № 5009\n05.03.2026 г., 10:01 Диспетчеров Д. Д.', 'В работе'),
        ['', None, None, None, None, None, None, None, None, None, None, None, None, None, None],
        row('abc', d(6, 1), 'битая строка', None, 'ул. Тихая, 4', '', 'В работе'),
    ]:
        ws.append(r)
    wb.save(path)
    return path
